const plain = (t: string) =>
  t
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();

/** Seção provável do item; "outros" se nenhuma palavra bater. Compara palavras inteiras. */
export function guessSection(text: string): Section {
  const t = ` ${plain(text).replace(/[^a-z0-9 -]/g, " ")} `;
  for (const [section, words] of KEYWORDS)
    if (words.some((w) => new RegExp(`[ -]${plain(w)}(s|es)?[ -]`).test(t))) return section;
  return "outros";
}
